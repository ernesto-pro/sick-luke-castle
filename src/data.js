export const formatViews = (value) => {
  if (!value) return ''
  if (value >= 1000000) {
    const millions = value / 1000000
    return `${millions >= 10 ? Math.round(millions) : millions.toFixed(1).replace('.0', '')}M`
  }
  if (value >= 1000) return `${Math.round(value / 1000)}K`
  return String(value)
}

